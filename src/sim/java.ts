import { afterCode, bodyCode, condCode, initCode, updCode } from './codegen';
import type { Problem } from './types';

/**
 * Wrap the learner facing loop in logging probes and return a complete Java
 * program. The loop header, condition, update, and body are the exact text
 * the learner sees; the probes only observe:
 *
 *   for (int i = 2; T.check(i, i < 10, st); i += 3, T.update(i, st)) {
 *       sum = sum + i;
 *       T.body(i, st);
 *   }
 *
 * `System.out` is redirected into a buffer so printed output can be attributed
 * to the step that printed it. The program prints the same transcript format as
 * `transcript()` in simulate.ts, and CI compares the two exactly.
 */
export function instrumentedJava(p: Problem, className: string): string {
  const v = p.v;
  const st = p.decls.length ? p.decls.map((d) => `" | ${d.name}=" + ${d.name}`).join(' + ') : '""';
  const lines: string[] = [];
  lines.push(`// Generated by scripts/verify-java.ts from problem ${p.id}. Do not edit.`);
  lines.push(`public class ${className} {`);
  lines.push(`    public static void main(String[] args) {`);
  lines.push(`        T.begin();`);
  for (const d of p.decls) lines.push(`        int ${d.name} = ${d.init};`);
  lines.push(`        for (${initCode(p)}; T.check(${v}, ${condCode(p)}, ${st}); ${updCode(p)}, T.update(${v}, ${st})) {`);
  lines.push(`            ${bodyCode(p)}`);
  lines.push(`            T.body(${v}, ${st});`);
  lines.push(`        }`);
  for (const a of p.after) lines.push(`        ${afterCode(a.name)}`);
  lines.push(`        T.end(${st});`);
  lines.push(`    }`);
  lines.push(`}`);
  lines.push('');
  lines.push(`final class T {`);
  lines.push(`    private static final java.io.PrintStream REAL = System.out;`);
  lines.push(`    private static final java.io.ByteArrayOutputStream BUF = new java.io.ByteArrayOutputStream();`);
  lines.push(`    private static int mark = 0;`);
  lines.push(`    private static boolean started = false;`);
  lines.push(``);
  lines.push(`    static void begin() { System.setOut(new java.io.PrintStream(BUF, true)); }`);
  lines.push(``);
  lines.push(`    private static String out() {`);
  lines.push(`        System.out.flush();`);
  lines.push(`        String all = BUF.toString();`);
  lines.push(`        String d = all.substring(mark);`);
  lines.push(`        mark = all.length();`);
  lines.push(`        return q(d);`);
  lines.push(`    }`);
  lines.push(``);
  lines.push(`    static boolean check(int v, boolean c, String st) {`);
  lines.push(`        if (!started) { started = true; REAL.println("INIT ${v}=" + v + st + " | out=" + out()); }`);
  lines.push(`        REAL.println("CHECK ${v}=" + v + " " + c + st + " | out=" + out());`);
  lines.push(`        return c;`);
  lines.push(`    }`);
  lines.push(``);
  lines.push(`    static void body(int v, String st) { REAL.println("BODY ${v}=" + v + st + " | out=" + out()); }`);
  lines.push(``);
  lines.push(`    static void update(int v, String st) { REAL.println("UPDATE ${v}=" + v + st + " | out=" + out()); }`);
  lines.push(``);
  lines.push(`    static void end(String st) { REAL.println("AFTER" + st + " | out=" + out()); REAL.flush(); }`);
  lines.push(``);
  lines.push(`    static String q(String s) {`);
  lines.push(`        s = s.replace("\\r\\n", "\\n");`);
  lines.push(`        StringBuilder b = new StringBuilder("\\"");`);
  lines.push(`        for (char ch : s.toCharArray()) {`);
  lines.push(`            switch (ch) {`);
  lines.push(`                case '\\\\': b.append("\\\\\\\\"); break;`);
  lines.push(`                case '"': b.append("\\\\\\""); break;`);
  lines.push(`                case '\\n': b.append("\\\\n"); break;`);
  lines.push(`                case '\\r': b.append("\\\\r"); break;`);
  lines.push(`                case '\\t': b.append("\\\\t"); break;`);
  lines.push(`                default: b.append(ch);`);
  lines.push(`            }`);
  lines.push(`        }`);
  lines.push(`        return b.append('"').toString();`);
  lines.push(`    }`);
  lines.push(`}`);
  lines.push('');
  return lines.join('\n');
}
